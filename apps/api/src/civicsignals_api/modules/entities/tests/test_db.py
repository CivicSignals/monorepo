@pytest.mark.asyncio
async def test_search_cursor_pagination(session: AsyncSession) -> None:
    async with session.begin():
        await seeding.seed_entities(session)
    total = (await _counts(session))["entity"]

    seen: list[uuid.UUID] = []
    cursor: str | None = None
    pages = 0
    while True:
        page = await services.search_entities(session, cursor=cursor, limit=5)
        seen.extend(e.id for e in page.items)
        pages += 1
        if page.next_cursor is None:
            break
        cursor = page.next_cursor
        assert pages < 50, "pagination did not terminate"

    # Walked every row exactly once, in id order, across multiple pages.
    assert len(seen) == total
    assert len(set(seen)) == total
    assert seen == sorted(seen)
    assert pages > 1


