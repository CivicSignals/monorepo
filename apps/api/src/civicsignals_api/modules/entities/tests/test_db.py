@pytest.mark.asyncio
async def test_public_routes_list_get_children(session: AsyncSession) -> None:
    """The public read endpoints serve the directory without X-Workspace-Id (C1 req 5).

    Driven through an in-process ASGI transport (``httpx.AsyncClient``) so the
    request runs in the test's event loop. The endpoint dependency is overridden
    with a fresh session per request (bound to the same engine) so the route's
    own session lifecycle is exercised, independent of the seeding session.
    """
    import httpx

    from civicsignals_api.db import get_session
    from civicsignals_api.main import app

    async with session.begin():
        await seeding.seed_entities(session)
    wa_state_id = (
        await session.execute(select(Entity.id).where(Entity.type == "state", Entity.state == "WA"))
    ).scalar_one()
    await session.rollback()

    assert _DSN is not None
    engine = create_async_engine(_DSN)

    async def _override() -> AsyncIterator[AsyncSession]:
        async with AsyncSession(engine) as req_session:
            yield req_session

    app.dependency_overrides[get_session] = _override
    transport = httpx.ASGITransport(app=app)
    try:
        async with httpx.AsyncClient(transport=transport, base_url="http://test") as client:
            # List with a kind+state filter; no workspace header supplied on purpose.
            resp = await client.get(
                "/api/v1/entities", params={"kind": "school_district", "state": "TX"}
            )
            assert resp.status_code == 200
            body = resp.json()
            assert body["items"]
            assert all(e["type"] == "school_district" and e["state"] == "TX" for e in body["items"])

            # Fetch one, then its children via the hierarchy endpoint.
            get_resp = await client.get(f"/api/v1/entities/{wa_state_id}")
            assert get_resp.status_code == 200
            assert get_resp.json()["name"] == "State of Washington"

            kids = await client.get(f"/api/v1/entities/{wa_state_id}/children")
            assert kids.status_code == 200
            assert kids.json()["items"]

            # Unknown id -> RFC 7807 problem+json 404.
            missing = await client.get(f"/api/v1/entities/{uuid.uuid4()}")
            assert missing.status_code == 404
            assert "application/problem+json" in missing.headers["content-type"]
    finally:
        app.dependency_overrides.pop(get_session, None)
        await engine.dispose()
