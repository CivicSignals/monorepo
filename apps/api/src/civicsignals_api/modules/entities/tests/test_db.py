"""DB-backed tests for the entities schema, seeder, and service API (C1).

These run against a live Postgres resolved from (in order) ``ENTITIES_TEST_DSN``,
``DATABASE_DIRECT_URL``, or ``DATABASE_URL`` — so they execute automatically in CI
(which sets ``DATABASE_DIRECT_URL`` to a throwaway ``civicsignals_test`` DB) and
for any dev with the stack up, while skipping cleanly when no DB is configured.
This is the same opt-in-via-env convention as ``tests/test_seed_demo.py``, but
wired to the CI DSN so the schema/seed actually get exercised in CI.

The DSN must be an ``asyncpg`` URL, e.g.::

    ENTITIES_TEST_DSN=postgresql+asyncpg://civic:civic@localhost:55432/civicsignals

Each test runs against a throwaway schema created fresh from the SQLAlchemy
metadata (plus the ``pg_trgm`` extension the trigram index needs), so they do not
depend on migration ordering and never touch another module's tables. A separate
test applies the *actual Alembic migration* to confirm the generated DDL works.
"""

from __future__ import annotations

import os
import uuid
from collections.abc import AsyncIterator
from types import ModuleType

import pytest
import pytest_asyncio
from sqlalchemy import Connection, Table, func, select, text
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine

from civicsignals_api.db import Base
from civicsignals_api.modules.entities import seeding, services
from civicsignals_api.modules.entities.models import Entity, EntityKind, Geo

_DSN = (
    os.environ.get("ENTITIES_TEST_DSN")
    or os.environ.get("DATABASE_DIRECT_URL")
    or os.environ.get("DATABASE_URL")
)
pytestmark = pytest.mark.skipif(_DSN is None, reason="no Postgres DSN configured")

# Only the entities tables — never drop another module's tables.
_TABLES: list[Table] = [
    Base.metadata.tables[name] for name in ("entities_entity", "entities_kind", "entities_geo")
]


@pytest_asyncio.fixture
async def session() -> AsyncIterator[AsyncSession]:
    assert _DSN is not None
    engine = create_async_engine(_DSN)
    async with engine.begin() as conn:
        await conn.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
        await conn.run_sync(Base.metadata.drop_all, tables=_TABLES)
        await conn.run_sync(Base.metadata.create_all, tables=_TABLES)
    try:
        async with AsyncSession(engine) as sess:
            yield sess
    finally:
        async with engine.begin() as conn:
            await conn.run_sync(Base.metadata.drop_all, tables=_TABLES)
        await engine.dispose()


async def _counts(session: AsyncSession) -> dict[str, int]:
    out: dict[str, int] = {}
    for name, model in (("entity", Entity), ("kind", EntityKind), ("geo", Geo)):
        result = await session.execute(select(func.count()).select_from(model))
        out[name] = int(result.scalar_one())
    # Close the implicit read transaction so callers can ``session.begin()`` again.
    await session.rollback()
    return out


def _load_migration_module() -> ModuleType:
    """Import the C1 migration by file path (alembic/versions isn't a package)."""
    import importlib.util
    from pathlib import Path

    # tests/ -> entities/ -> modules/ -> civicsignals_api/ -> src/ -> apps/api/
    api_root = Path(__file__).resolve().parents[5]
    path = api_root / "alembic" / "versions" / "f8de6b788783_entities_kind_geo_entity_tables.py"
    spec = importlib.util.spec_from_file_location("c1_entities_migration", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _run_migration_upgrade(conn: Connection) -> set[str]:
    """Run the entities migration's ``upgrade()`` on a *sync* connection.

    Driven via ``AsyncConnection.run_sync`` so it works with the asyncpg engine
    (no separate sync driver needed). Returns the ``entities_*`` table names that
    exist afterwards.
    """
    from alembic.operations import Operations
    from alembic.runtime.migration import MigrationContext

    migration = _load_migration_module()
    for tbl in ("entities_entity", "entities_kind", "entities_geo"):
        conn.exec_driver_sql(f"DROP TABLE IF EXISTS {tbl} CASCADE")
    with Operations.context(MigrationContext.configure(conn)):
        migration.upgrade()
    rows = conn.exec_driver_sql(
        "SELECT tablename FROM pg_tables WHERE tablename LIKE 'entities_%'"
    ).fetchall()
    return {r[0] for r in rows}


@pytest.mark.asyncio
async def test_entities_migration_applies(session: AsyncSession) -> None:
    """The generated Alembic DDL creates exactly the three entity tables on PG.

    Drops the metadata-created tables, then runs the migration's own
    ``upgrade()`` ops body against a clean slate, proving the autogenerated DDL
    is valid Postgres and touches only ``entities_*`` objects.
    """
    assert _DSN is not None
    engine = create_async_engine(_DSN)
    try:
        async with engine.begin() as conn:
            tables = await conn.run_sync(_run_migration_upgrade)
        assert tables == {"entities_entity", "entities_kind", "entities_geo"}
    finally:
        await engine.dispose()


